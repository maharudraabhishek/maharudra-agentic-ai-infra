import type { RuntimeMode } from "../runtime/types.js";
import type { FrameworkResult } from "../errors/index.js";

/**
 * A live or recently-closed agent session.
 *
 * A session represents one developer context window: a user client connected to
 * the framework for some period of time. It spans multiple threads (goals) and
 * survives short idle gaps via `touchSession`. The session lifecycle is:
 *   create → active → idle (touch to reset) → closed.
 *
 * Sessions are project-scoped so the dashboard can aggregate cost and latency
 * per project without storing raw task text.
 */
export type AgentSession = {
  /** Stable UUID. Primary key in agentic_sessions. */
  readonly sessionId: string;
  /** Owning project — matches config.project.slug or name. */
  readonly projectId: string;
  /** Originating client identifier, e.g. "claude-code", "cursor", "api". */
  readonly client: string;
  /** Runtime mode active when the session was opened. */
  readonly runtimeMode: RuntimeMode;
  /** Lifecycle state of the session. */
  readonly status: "active" | "idle" | "closed";
  /** When the session was first created. */
  readonly startedAt: Date;
  /** Wall-clock time of the most recent activity (tool call or touch). */
  readonly lastSeenAt: Date;
  /** Caller-supplied key/value pairs for routing or display. Never store secrets here. */
  readonly metadata: Record<string, string>;
};

/**
 * One goal within a session.
 *
 * A thread holds safe task metadata and a state summary so the dashboard can
 * show what each agent is working on without storing raw task text.
 * Multiple threads can exist under one session (sequentially, not concurrently).
 *
 * The thread lifecycle is: open → completed | failed.
 */
export type AgentThread = {
  /** Stable UUID. Primary key in agentic_threads. */
  readonly threadId: string;
  /** Foreign key into agentic_sessions. */
  readonly sessionId: string;
  /** Safe `taskType`/`taskHash` display label. Raw user goals are forbidden. */
  readonly userGoal: string;
  /** The tool or sub-task currently executing, if any. */
  readonly activeTask: string | undefined;
  /** Compact free-text summary of where execution left off. */
  readonly stateSummary: string | undefined;
  /** Lifecycle state of the thread. */
  readonly status: "open" | "completed" | "failed";
  /** When the thread was opened. */
  readonly createdAt: Date;
  /** When the thread was last updated. */
  readonly updatedAt: Date;
};

/**
 * One tool call recorded within a thread.
 *
 * `inputHash` and `outputHash` are SHA-256 digests of the JSON-serialized
 * input/output, not the raw values themselves. This keeps the record safe for
 * dashboard queries while still enabling dedup and freshness checks.
 */
export type ThreadedToolCall = {
  /** Stable UUID generated at record time. */
  readonly callId: string;
  /** Foreign key into agentic_threads. */
  readonly threadId: string;
  /** The tool contract id. */
  readonly toolName: string;
  /** SHA-256 of JSON.stringify(input). */
  readonly inputHash: string;
  /** SHA-256 of JSON.stringify(sanitizedOutput). Absent until the call completes. */
  readonly outputHash: string | undefined;
  /** Execution outcome. */
  readonly status: "pending" | "success" | "failed";
  /** When the tool call began. */
  readonly startedAt: Date;
  /** When the tool call ended. Absent until the call completes. */
  readonly completedAt: Date | undefined;
  /** Stable error code if status is "failed". */
  readonly errorCode: string | undefined;
  /** Heuristic token estimate for the tool call, if available. */
  readonly tokenEstimate: number | undefined;
};

/**
 * Parameters required to open a new session.
 *
 * The `sessionId` is generated by `createSession`; callers do not supply it.
 * Callers supply project identity, client label, and runtime mode so the
 * dashboard can slice cost and latency by project and client.
 */
export type CreateSessionParams = {
  /** Project identifier matching `config.project.slug`. */
  readonly projectId: string;
  /** Client identifier, e.g. "claude-code", "cursor", "api". */
  readonly client: string;
  /** Runtime mode the session is operating under. */
  readonly runtimeMode: RuntimeMode;
  /** Optional key/value metadata. Keys and values must not contain secrets. */
  readonly metadata?: Record<string, string>;
};

/**
 * Session and thread lifecycle manager.
 *
 * The `SessionManager` interface is deliberately small so implementations can
 * stay in-memory (for vectorless-local profiles) or Postgres-backed without
 * callers needing to know which. All capability checks are duck-typed:
 *
 * ```ts
 * // Do NOT do this:
 * if (manager instanceof PostgresSessionManager) { ... }
 *
 * // Do this instead:
 * const session = await manager.createSession(params);
 * ```
 *
 * Implementations: `PostgresSessionManager`, `InMemorySessionManager`.
 * Factory: `createSessionManager(db)`.
 */
export interface SessionManager {
  /**
   * Opens a brand-new session.
   *
   * Generates a new `sessionId` via `crypto.randomUUID()`, persists the record,
   * and returns the full `AgentSession` on success.
   *
   * @param params - Project, client, mode, and optional metadata.
   * @returns The new session or a `session.create-failed` error.
   */
  createSession(params: CreateSessionParams): Promise<FrameworkResult<AgentSession>>;

  /**
   * Resumes an existing session or creates a new one.
   *
   * If `sessionId` resolves to an existing record, `last_seen_at` is updated and
   * the existing session is returned. If not found, a new session is created using
   * `params`.
   *
   * Use this in `execute()` rather than `createSession()` so agent re-runs
   * within the same client window reuse the same session row.
   *
   * @param sessionId - ID to look up.
   * @param params - Fallback params used when creating a new session.
   * @returns The resumed or newly created session.
   */
  resumeOrCreateSession(
    sessionId: string,
    params: CreateSessionParams
  ): Promise<FrameworkResult<AgentSession>>;

  /**
   * Bumps `last_seen_at` to now.
   *
   * Call after successful `execute()` to prevent the session from becoming idle.
   *
   * @param sessionId - The session to touch.
   * @returns `ok(undefined)` or a `session.not-found` error.
   */
  touchSession(sessionId: string): Promise<FrameworkResult<void>>;

  /**
   * Marks the session as closed.
   *
   * Closed sessions are retained for dashboard queries but no further tool calls
   * should be recorded against them.
   *
   * @param sessionId - The session to close.
   * @returns `ok(undefined)` or a `session.not-found` error.
   */
  closeSession(sessionId: string): Promise<FrameworkResult<void>>;

  /**
   * Opens a new thread under an existing session.
   *
   * Each call to `execute()` opens one thread. Executors pass a bounded
   * `taskType`/`taskHash` label rather than raw task or prior-agent text.
   *
   * @param sessionId - Parent session.
   * @param userGoal - Safe metadata label; raw task, synthesis, and secrets are forbidden.
   * @returns The new thread or a `session.thread-open-failed` error.
   */
  openThread(
    sessionId: string,
    userGoal: string
  ): Promise<FrameworkResult<AgentThread>>;

  /**
   * Applies a partial update to an existing thread.
   *
   * Safe to call with any subset of `activeTask`, `stateSummary`, or `status`.
   * Always updates `updatedAt` to now.
   *
   * @param threadId - The thread to update.
   * @param update - Fields to change.
   * @returns `ok(undefined)` or a `session.not-found` error.
   */
  updateThread(
    threadId: string,
    update: Partial<Pick<AgentThread, "activeTask" | "stateSummary" | "status">>
  ): Promise<FrameworkResult<void>>;

  /**
   * Persists one tool call record.
   *
   * Generates `callId` internally via `crypto.randomUUID()`. The caller provides
   * all other fields. `inputHash` and `outputHash` must be pre-computed SHA-256
   * digests, never raw values.
   *
   * @param call - All fields except `callId`.
   * @returns The stored record with `callId` set, or a `session.tool-call-record-failed` error.
   *
   * @example
   * const hash = (v: unknown) => createHash("sha256").update(JSON.stringify(v)).digest("hex");
   * await sessionManager.recordToolCall({
   *   threadId: thread.threadId,
   *   toolName: "agentic.retrieval.search",
   *   inputHash: hash(input),
   *   outputHash: hash(output),
   *   status: "success",
   *   startedAt: new Date(),
   *   completedAt: new Date(),
   *   errorCode: undefined,
   *   tokenEstimate: 42
   * });
   */
  recordToolCall(
    call: Omit<ThreadedToolCall, "callId">
  ): Promise<FrameworkResult<ThreadedToolCall>>;
}
